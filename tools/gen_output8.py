#!/usr/bin/env python3
"""Eight independent counter-zero compressions (Linux AVX2).

(params, out), System V: read-only Params8 is 384 bytes, aligned64:
MSG[8] pointers at0, CV[8][8] word-major u32 at64, LENS[8] at320,
FLAGS[8] at352. Each pointer reaches64 bytes; each length is0..64.
Flags select CVs or roots. out holds eight canonical32-byte values.
All input data is read before output stores. No calls/allocation.
The shared partial-kernel emitter supplies the seven-round compression.
"""
import gen_x86 as shared

class Output8(shared.Kernel):
    def pm(self, name, extra=0):
        if name in ('IV', 'ROT16', 'ROT8', 'CTR'):
            return self.mem('rip', f'.Lout8_{name.lower()} + {extra}')
        return super().pm(name, extra)

k = Output8('avx2')
# Keep the shared body unchanged. Its compression prefix consumes one block;
# the snapshot/block-loop tail belongs to the partial kernel's other contract.
k.off.update(MSG=0, KEY=64, LENS=320, FLAGS=352)
k.body('blake3_servil_output8')
marker = f"        cmp edx, dword ptr [rdi+{k.off['LAST']}]"
assert k.lines.count(marker) == 1
lines = k.lines[:k.lines.index(marker)]
assert sum('blake3_servil_output8_block:' == line for line in lines) == 1
# Counter zero is two zero vectors, preserving the shared row-c spill layout.
for register, offset in [(12,0),(13,32)]:
    old = f'        vmovdqu ymm{register}, ymmword ptr [rip+.Lout8_ctr + {offset}]'
    assert lines.count(old) == 1, old
    lines[lines.index(old)] = f'        vpxor ymm{register}, ymm{register}, ymm{register}'

# Eight word-major CVs -> eight message-major CVs, with one rotating scratch.
rows, scratch = list(range(8)), 8
for distance, low, high, loimm, hiimm in [
    (1,'vpunpckldq','vpunpckhdq','',''),
    (2,'vpunpcklqdq','vpunpckhqdq','',''),
    (4,'vperm2i128','vperm2i128',', 0x20',', 0x31')]:
    for base in range(0,8,2*distance):
        for i in range(base,base+distance):
            j=i+distance;a,b=rows[i],rows[j]
            lines += [f'        {low} ymm{scratch}, ymm{a}, ymm{b}{loimm}',
                      f'        {high} ymm{a}, ymm{a}, ymm{b}{hiimm}']
            rows[i],rows[j],scratch = scratch,a,b
            assert len(set(rows+[scratch])) == 9
for i, word in enumerate([0,2,1,3,4,6,5,7]):
    lines.append(f'        vmovdqu ymmword ptr [rsi+{32*i}], ymm{rows[word]}')
lines += ['        vzeroupper','        mov rsp, rbp']
for g in ['r15','r14','r13','r12','rbx','rbp']:
    lines.append(f'        pop {g}')
lines.append('        ret')
print('// Generated by tools/gen_output8.py; read-only Params8 contract in its header.')
print('.intel_syntax noprefix\n.text\n.p2align 6\n.global blake3_servil_output8\n.hidden blake3_servil_output8\n.type blake3_servil_output8, @function\nblake3_servil_output8:\n    endbr64')
print('\n'.join(lines))
print('.size blake3_servil_output8, .-blake3_servil_output8\n.section .rodata\n.p2align 6\n.Lout8_iv:')
for word in [0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a]:
    print('.long '+', '.join([hex(word)]*8))
for name, shift in [('rot16',2),('rot8',1)]:
    print(f'.Lout8_{name}:')
    mask = [4*(j//4)+(j+shift)%4 for j in range(16)] * 2
    print('.byte '+', '.join(map(str, mask)))
print('.section .note.GNU-stack,"",@progbits')
