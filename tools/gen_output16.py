#!/usr/bin/env python3
"""Generate a 16-lane root-output compression kernel (Linux AVX-512F+VL).

(inputs, out): inputs is 16 repr(C) descriptors of stride 24:
block pointer at 0 (64 readable bytes), CV pointer at 8 (eight readable u32),
block length byte at 16 (0..64), flags byte at 17. Blocks are zero-padded.
Each compression uses counter zero and the descriptor's flags in every lane.
Each lane has its own CV, length and flags. out holds 16 canonical 32-byte
chaining values (root digests when ROOT is present). All input data is read before output stores. No calls or allocation.
"""
import ast
import pathlib

source = pathlib.Path(__file__).with_name('gen_avx512_32.py').read_text()
module = ast.parse(source)
functions = {'emit', 'transpose', 'output_group', 'g'}
constants = {'IV', 'PERM', 'COLS', 'DIAGS', 'WORD'}
nodes = [n for n in module.body if
         isinstance(n, ast.FunctionDef) and n.name in functions or
         isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id in constants for t in n.targets)]
assert len(nodes) == len(functions) + len(constants)
ns = {}
exec(compile(ast.Module(body=nodes, type_ignores=[]), 'shared_avx512_emitters', 'exec'), ns)
emit, transpose, g = ns['emit'], ns['transpose'], ns['g']
print('// Generated by tools/gen_output16.py; root-output descriptor contract in its header.')
print('.intel_syntax noprefix\n.text\n.p2align 6\n.global blake3_servil_output16\n.hidden blake3_servil_output16\n.type blake3_servil_output16, @function\nblake3_servil_output16:\n.cfi_startproc')
emit('endbr64')
emit('push rbp')
print('.cfi_def_cfa_offset 16\n.cfi_offset rbp, -16')
emit('mov rbp, rsp')
print('.cfi_def_cfa_register rbp')
emit('push r15')
print('.cfi_offset r15, -24')
emit('and rsp, -64')
emit('sub rsp, 384')
emit('mov r15, rsi')
for i in range(16):
    emit(f'mov rax, QWORD PTR [rdi + {24*i+8}]')
    emit(f'vmovdqu32 ymm{16+i}, YMMWORD PTR [rax]')
    emit(f'movzx edx, BYTE PTR [rdi + {24*i+16}]')
    emit(f'mov DWORD PTR [rsp + {256+4*i}], edx')
    emit(f'movzx edx, BYTE PTR [rdi + {24*i+17}]')
    emit(f'mov DWORD PTR [rsp + {320+4*i}], edx')
rows = transpose(list(range(16, 32)), 8)
for w in range(8):
    emit(f'vmovdqa32 zmm{w}, zmm{rows[ns["WORD"][w]]}')
for i in range(16):
    emit(f'mov rax, QWORD PTR [rdi + {24*i}]')
    emit(f'vmovdqu32 zmm{16+i}, ZMMWORD PTR [rax]')
rows = transpose(list(range(16, 32)), 8)
messages = [rows[ns['WORD'][w]] for w in range(16)]
upper = [r for r in range(8, 32) if r not in messages]
registers = list(range(8)) + upper
assert len(upper) == 8 and len(set(registers + messages)) == 32
for w in range(4):
    emit(f'vpbroadcastd zmm{registers[8+w]}, DWORD PTR [rip + .Loutput_iv + {4*w}]')
for w in [12, 13]:
    r = registers[w]
    emit(f'vpxord zmm{r}, zmm{r}, zmm{r}')
emit(f'vmovdqa32 zmm{registers[14]}, ZMMWORD PTR [rsp + 256]')
emit(f'vmovdqa32 zmm{registers[15]}, ZMMWORD PTR [rsp + 320]')
perm = ns['PERM']
p2 = [perm[perm[i]] for i in range(16)]
cycles, seen = [], set()
for start in range(16):
    if start in seen:
        continue
    cycle, word = [], start
    while word not in seen:
        seen.add(word)
        cycle.append(word)
        word = p2[word]
    assert word == start
    cycles.append(cycle)
assert len(cycles) == 4 and all(len(c) == 4 for c in cycles)
emit('mov r11d, 7')
print('.p2align 5\n.Loutput_round:')
for schedule in (list(range(16)), perm):
    for half, positions in enumerate((ns['COLS'], ns['DIAGS'])):
        chains = [g(*[f'zmm{registers[w]}' for w in pos],
                    f'zmm{messages[schedule[8*half+2*i]]}',
                    f'zmm{messages[schedule[8*half+2*i+1]]}')
                  for i, pos in enumerate(positions)]
        for instructions in zip(*chains):
            for instruction in instructions:
                emit(instruction)
    emit('dec r11d')
    if schedule == list(range(16)):
        emit('jz .Loutput_done')
for i, cycle in enumerate(cycles):
    emit(f'vmovdqa32 ZMMWORD PTR [rsp + {64*i}], zmm{messages[cycle[0]]}')
    for a, b in zip(cycle, cycle[1:]):
        emit(f'vmovdqa32 zmm{messages[a]}, zmm{messages[b]}')
    emit(f'vmovdqa32 zmm{messages[cycle[-1]]}, ZMMWORD PTR [rsp + {64*i}]')
emit('jmp .Loutput_round')
print('.Loutput_done:')
for w in range(8):
    emit(f'vpxord zmm{w}, zmm{w}, zmm{registers[8+w]}')
ns['output_group'](0, 0)
emit('vzeroupper')
emit('lea rsp, [rbp - 8]')
emit('pop r15')
print('.cfi_restore r15')
emit('pop rbp')
print('.cfi_def_cfa rsp, 8\n.cfi_restore rbp')
emit('ret')
print('.cfi_endproc\n.size blake3_servil_output16, .-blake3_servil_output16')
print('.section .rodata\n.p2align 6\n.Loutput_iv:\n.long ' + ', '.join(hex(w) for w in ns['IV']))
print('.section .note.GNU-stack,"",@progbits')
